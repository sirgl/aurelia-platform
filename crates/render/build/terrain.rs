//! Terrain props: the "terrain" section of platform/assets/models/manifest.json +
//! platform/assets/models/terrain/*.glb (platform/tools/blender/export_terrain.py) -> baked LOD0 vertices.
//!
//! Validates every model against its budget class (triangles per LOD, footprint radius,
//! height, grounding), the palette and the declared files. Writes
//! OUT_DIR/terrain_models.rs with `SEA_STACK_MESHES` (one UnitVertex slice per variant).

use crate::glb::{self, extent, Problems, LOD_NODES};
use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

/// Distance a vertex may lie outside its declared bounds or shape.
const EPS: f32 = 2e-3;

#[derive(Deserialize)]
struct Root {
    palette: BTreeMap<String, [f32; 3]>,
    terrain: Terrain,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Terrain {
    #[allow(dead_code)]
    generator: String,
    #[allow(dead_code)]
    note: String,
    #[allow(dead_code)]
    axes: String,
    budgets: BTreeMap<String, [usize; 3]>,
    /// Budget class -> (max footprint radius, max height, lowest allowed point).
    shapes: BTreeMap<String, [f32; 3]>,
    models: Vec<Entry>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    id: String,
    file: String,
    budget: String,
    bounds: Bounds,
    radius: f32,
    materials: Vec<String>,
    lods: Vec<Lod>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Bounds {
    min: [f32; 3],
    max: [f32; 3],
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Lod {
    node: String,
    tris: usize,
}

pub fn bake(root: &Path, out_dir: &Path) {
    let models_dir = root.join("assets/models");
    let manifest_path = models_dir.join("manifest.json");
    println!("cargo:rerun-if-changed={}", models_dir.join("terrain").display());
    let text = std::fs::read_to_string(&manifest_path)
        .unwrap_or_else(|e| panic!("terrain models: cannot read {}: {e}", manifest_path.display()));
    let manifest: Root = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("terrain models: {} is malformed: {e}", manifest_path.display()));
    let (palette, t) = (manifest.palette, manifest.terrain);
    let mut p = Problems(Vec::new());
    let mut stacks = Vec::new();
    let mut declared = BTreeSet::new();
    for e in &t.models {
        declared.insert(models_dir.join(&e.file));
        let (Some(budget), Some(shape)) = (t.budgets.get(&e.budget), t.shapes.get(&e.budget)) else {
            p.add(format!("{}: unknown budget class {}", e.id, e.budget));
            continue;
        };
        let src = glb::Source { id: &e.id, file: &e.file, pivot: [0.0; 3], scale: 1.0 };
        let Some(lods) = glb::load_lods(&models_dir, &src, &mut p) else { continue };
        for (k, mesh) in lods.iter().enumerate() {
            glb::check_mesh(&palette, &e.id, LOD_NODES[k], &e.materials, mesh, &mut p);
            if mesh.triangles() > budget[k] {
                p.add(format!("{} {}: {} tris exceed the {} budget {}", e.id, LOD_NODES[k], mesh.triangles(), e.budget, budget[k]));
            }
            if e.lods.get(k).map(|l| (l.node.as_str(), l.tris)) != Some((LOD_NODES[k], mesh.triangles())) {
                p.add(format!("{} {}: manifest lod entry does not match the GLB", e.id, LOD_NODES[k]));
            }
            if mesh.team.iter().any(|&m| m != 0.0) {
                p.add(format!("{} {}: terrain props carry no team color", e.id, LOD_NODES[k]));
            }
        }
        let (lo, hi) = extent(&lods[0].pos);
        let radius = lods[0].pos.iter().map(|v| v[0].hypot(v[2])).fold(0f32, f32::max);
        let [max_radius, max_height, lowest] = *shape;
        if radius > max_radius + EPS || hi[1] > max_height + EPS || lo[1] < lowest - EPS {
            p.add(format!("{}: radius {radius}, height {}..{} outside the {} shape {shape:?}", e.id, lo[1], hi[1], e.budget));
        }
        if (radius - e.radius).abs() > EPS
            || (0..3).any(|k| (lo[k] - e.bounds.min[k]).abs() > EPS || (hi[k] - e.bounds.max[k]).abs() > EPS)
        {
            p.add(format!("{}: manifest bounds or radius do not match the GLB", e.id));
        }
        if e.budget == "sea-stack" {
            stacks.push(lods.into_iter().next().expect("LOD0"));
        }
    }
    glb::check_stray_files(&models_dir.join("terrain"), &declared, "terrain", &mut p);
    if stacks.is_empty() {
        p.add("terrain: no sea-stack model".into());
    }
    if !p.0.is_empty() {
        panic!("terrain models:\n  {}", p.0.join("\n  "));
    }
    let mut code = String::from("// @generated by build.rs from the terrain section of assets/models/manifest.json — do not edit.\n");
    code.push_str("pub const SEA_STACK_MESHES: &[&[crate::gpu::buffers::UnitVertex]] = &[\n");
    for mesh in &stacks {
        code.push_str("    &[");
        for t in 0..mesh.triangles() {
            let [a, b, c] = [mesh.pos[3 * t], mesh.pos[3 * t + 1], mesh.pos[3 * t + 2]];
            let n = glb::cross(glb::sub(b, a), glb::sub(c, a));
            let len = (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt();
            for k in 0..3 {
                let (v, rgb) = (mesh.pos[3 * t + k], mesh.rgb[3 * t + k]);
                let _ = write!(
                    code,
                    "crate::gpu::buffers::UnitVertex {{ pos: [{:.5}, {:.5}, {:.5}], normal: [{:.5}, {:.5}, {:.5}], color: [{:.5}, {:.5}, {:.5}], team: 0.0 }},",
                    v[0], v[1], v[2], n[0] / len, n[1] / len, n[2] / len, rgb[0], rgb[1], rgb[2]
                );
            }
        }
        code.push_str("],\n");
    }
    code.push_str("];\n");
    std::fs::write(out_dir.join("terrain_models.rs"), code).unwrap();
}
